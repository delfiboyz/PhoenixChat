const DICT = { id, en };

// Tebakan awal dari bahasa sistem; pengguna memilih sendiri di layar Mulai.
export function detectLang() {
  const l = String((typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'id').toLowerCase();
  return l.startsWith('id') || l.startsWith('ms') ? 'id' : 'en';
}

let current = detectLang();

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'id';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const getLang = () => current;
export const locale = () => (current === 'en' ? 'en-GB' : 'id-ID');

export function t(key, vars) {
  let s = DICT[current][key] ?? DICT.id[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}
